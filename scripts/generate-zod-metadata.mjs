import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

function resolveZodFile(relativePath) {
  const zodPackageJsonPath = require.resolve('zod/package.json');
  return path.join(path.dirname(zodPackageJsonPath), relativePath);
}

function findMatchingBraceIndex(source, openBraceIndex) {
  let depth = 0;
  for (let i = openBraceIndex; i < source.length; i++) {
    const ch = source[i];
    if (ch === '{') {
      depth++;
      continue;
    }

    if (ch === '}') {
      depth--;
      if (depth === 0) {
        return i;
      }
    }
  }

  return -1;
}

function extractInstallLazyMethodNames(source, groupName) {
  const marker = `_installLazyMethods(inst, "${groupName}", {`;
  const markerIndex = source.indexOf(marker);
  if (markerIndex === -1) {
    throw new Error(`Could not find lazy method group "${groupName}" in zod classic schemas source.`);
  }

  const objectStart = source.indexOf('{', markerIndex);
  const objectEnd = findMatchingBraceIndex(source, objectStart);
  if (objectStart === -1 || objectEnd === -1) {
    throw new Error(`Could not parse lazy method object for "${groupName}".`);
  }

  const objectBody = source.slice(objectStart + 1, objectEnd);
  const methodNames = new Set();
  const methodPattern = /^\s*([A-Za-z_$][\w$]*)\s*\([^)]*\)\s*\{/gm;
  let match = null;

  while ((match = methodPattern.exec(objectBody)) !== null) {
    methodNames.add(match[1]);
  }

  return [...methodNames].sort();
}

function extractMiniCheckNames(source) {
  const names = new Set();
  const pattern = /\bas\s+([A-Za-z_$][\w$]*)/g;
  let match = null;

  while ((match = pattern.exec(source)) !== null) {
    names.add(match[1]);
  }

  return [...names].sort();
}

function renderArray(name, values) {
  return `export const ${name} = ${JSON.stringify(values)} as const;`;
}

function main() {
  const classicSchemasPath = resolveZodFile('v4/classic/schemas.js');
  const miniChecksPath = resolveZodFile('v4/mini/checks.js');

  const classicSchemasSource = fs.readFileSync(classicSchemasPath, 'utf8');
  const miniChecksSource = fs.readFileSync(miniChecksPath, 'utf8');

  const zodTypeMethodNames = extractInstallLazyMethodNames(classicSchemasSource, 'ZodType');
  const zodObjectMethodNames = extractInstallLazyMethodNames(classicSchemasSource, 'ZodObject');
  const miniCheckNames = extractMiniCheckNames(miniChecksSource);

  const generated = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-zod-metadata.mjs
// Do not edit manually.

${renderArray('GENERATED_ZOD_TYPE_METHODS', zodTypeMethodNames)}
${renderArray('GENERATED_ZOD_OBJECT_METHODS', zodObjectMethodNames)}
${renderArray('GENERATED_MINI_CHECK_METHODS', miniCheckNames)}
`;

  const outputPath = path.resolve(process.cwd(), 'src/lib/generated-zod-metadata.ts');
  fs.writeFileSync(outputPath, generated, 'utf8');
}

main();
